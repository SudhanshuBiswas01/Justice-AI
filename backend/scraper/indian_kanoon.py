class IndianKanoonScraper:
    def __init__(self):
        self.base_url = "https://indiankanoon.org"
        self.search_url = "https://indiankanoon.org/search/"
        
    def _get_headers(self) -> Dict[str, str]:
        return {
            'User-Agent': random.choice(USER_AGENTS),
            'Accept': 'text/html,application/xhtml+xml,application/xml;q=0.9,image/webp,*/*;q=0.8',
            'Accept-Language': 'en-US,en;q=0.5',
            'Connection': 'keep-alive',
        }

    def search(self, query: str, limit: int = 5) -> List[Dict[str, Any]]:
        """
        Searches Indian Kanoon for a keyword. If scraping fails (Cloudflare, connection error),
        it falls back to providing relevant mock judgments for testing.
        """
        print(f"[Indian Kanoon] Searching for query: '{query}'")
        
        # Try real scraping first
        try:
            params = {
                'formInput': query,
                'pagenum': 0
            }
            headers = self._get_headers()
            response = requests.get(self.search_url, params=params, headers=headers, timeout=10)
            
            if response.status_code == 200:
                soup = BeautifulSoup(response.text, 'html.parser')
                results = []
                
                # Search results titles are typically in divs with class 'result_title'
                title_divs = soup.find_all('div', class_='result_title')
                
                for div in title_divs[:limit]:
                    link_tag = div.find('a')
                    if link_tag and link_tag.get('href'):
                        href = link_tag.get('href')
                        title = link_tag.get_text().strip()
                        
                        # Extract document ID from link, e.g. /doc/12345/
                        doc_id = href.split('/')[-2] if href.endswith('/') else href.split('/')[-1]
                        
                        # Add a small delay to respect the server
                        time.sleep(random.uniform(1.0, 2.5))
                        
                        doc_data = self.fetch_document(doc_id)
                        if doc_data:
                            results.append(doc_data)
                            
                if results:
                    return results
                else:
                    print("[Indian Kanoon] Search parsed 0 results, falling back to mock judgments.")
            else:
                print(f"[Indian Kanoon] Search returned status code: {response.status_code}, falling back to mock judgments.")
        except Exception as e:
            print(f"[Indian Kanoon] Real scraping encountered an error: {e}. Falling back to mock judgments.")

        # FALLBACK: Provide high-quality mock data based on query match
        print("[Indian Kanoon] Returning matching mock judgments for demo queries...")
        query_lower = query.lower()
        results = []
        
        # Match keywords to mock documents
        if "mrp" in query_lower or "overcharg" in query_lower:
            mock_list = MOCK_JUDGMENTS["mrp_overcharging"]
        elif "challan" in query_lower or "traffic" in query_lower or "helmet" in query_lower:
            mock_list = MOCK_JUDGMENTS["traffic_challan"]
        elif "refund" in query_lower or "cancel" in query_lower or "e-commerce" in query_lower:
            mock_list = MOCK_JUDGMENTS["refund_dispute"]
        else:
            # Default to combining a couple of them if query is generic
            mock_list = MOCK_JUDGMENTS["mrp_overcharging"] + MOCK_JUDGMENTS["traffic_challan"]

        for item in mock_list[:limit]:
            doc_id = f"mock_kanoon_{abs(hash(item['title']))}"
            results.append({
                "id": doc_id,
                "title": item["title"],
                "content": item["content"],
                "url": f"https://indiankanoon.org/doc/{doc_id}/",
                "court": item["court"],
                "act_name": item["act_name"],
                "section": item["section"],
                "year": item["year"],
                "category": item["category"],
                "doc_type": "Judgment"
            })
            
        return results

    def fetch_document(self, doc_id: str) -> Optional[Dict[str, Any]]:
        """Fetches the full text of a document from Indian Kanoon."""
        url = f"{self.base_url}/doc/{doc_id}/"
        print(f"[Indian Kanoon] Fetching document text from: {url}")
        
        try:
            headers = self._get_headers()
            response = requests.get(url, headers=headers, timeout=10)
            
            if response.status_code == 200:
                soup = BeautifulSoup(response.text, 'html.parser')
                
                # Get title
                title_div = soup.find('div', class_='doc_title')
                title = title_div.get_text().strip() if title_div else f"Indian Kanoon Document {doc_id}"
                
                # Extract text inside divs with class 'judgments' or paragraph tags
                judgment_div = soup.find('div', class_='judgments')
                if judgment_div:
                    content = judgment_div.get_text()
                else:
                    # Fallback to paragraph tags
                    paragraphs = soup.find_all(['p', 'div'], id=lambda x: x and x.startswith('p_'))
                    if paragraphs:
                        content = "\n\n".join([p.get_text().strip() for p in paragraphs])
                    else:
                        # General body text extraction
                        content = soup.get_text()
                        
                return {
                    "id": f"kanoon_{doc_id}",
                    "title": title,
                    "content": content.strip(),
                    "url": url
                }
            else:
                print(f"[Indian Kanoon] Fetching document {doc_id} returned status: {response.status_code}")
                return None
        except Exception as e:
            print(f"[Indian Kanoon] Error fetching document {doc_id}: {e}")
            return None
